import mongoose from "mongoose";
import { env } from "../src/config/env";
import { ConversationModel } from "../src/models/Conversation.model";
import { MessageModel } from "../src/models/Message.model";
import { chatService, validateCitations } from "../src/services/chat.service";
import { rewriteQueryForFollowUp } from "../src/rag/generation/queryRewriter";
import {
  detectMetadataFromQuery,
  matchMetadataAgainstUserDocuments,
} from "../src/rag/retrieval/metadataFilter";
import { DocumentModel } from "../src/models/Document.model";
import {
  buildAnswerPrompt,
  buildNumberedContext,
  NOT_FOUND_MESSAGE,
  SYSTEM_PROMPT_V1,
  type ContextBlock,
} from "../src/rag/prompts/answer.v1";

async function runTest() {
  console.log("================================================================================");
  console.log("  FinSight AI - Step 9: Chat Models, Prompt & Flow Verification");
  console.log("================================================================================\n");

  try {
    await mongoose.connect(env.MONGODB_URI);
    console.log("✅ Connected to MongoDB for chat test.");

    const testUserId = new mongoose.Types.ObjectId();

    // --------------------------------------------------------------------------
    // Test 1: Step 9.1 Models (Conversation & Message)
    // --------------------------------------------------------------------------
    console.log("\n🧪 1. Testing Step 9.1 Models (Conversation & Message)...");

    const conversation = await ConversationModel.create({
      userId: testUserId,
      title: "Apple FY24 Financial Analysis",
    });

    console.log(`   ✓ Created Conversation ID: ${conversation._id}`);
    console.log(`   ✓ Title: "${conversation.title}"`);

    const sampleSource = {
      chunkId: new mongoose.Types.ObjectId(),
      documentId: new mongoose.Types.ObjectId(),
      title: "Apple_Inc_FY24_10K.pdf",
      page: 2,
      snippet: "Net income (Net Profit): $93,736 million ($93.7 billion).",
      score: 0.9421,
    };

    const userMsg = await MessageModel.create({
      conversationId: conversation._id,
      role: "user",
      content: "What was the net profit in FY24?",
      status: "completed",
    });

    const assistantMsg = await MessageModel.create({
      conversationId: conversation._id,
      role: "assistant",
      content: "For fiscal year 2024, Apple Inc. reported a net profit (net income) of $93.7 billion ($93,736 million) [1].",
      sources: [sampleSource],
      status: "completed",
    });

    console.log(`   ✓ Created User Message ID     : ${userMsg._id}`);
    console.log(`   ✓ Created Assistant Message ID: ${assistantMsg._id}`);
    console.log(`   ✓ Sources attached            : ${assistantMsg.sources.length} (Page ${assistantMsg.sources[0]?.page})`);

    const messages = await chatService.getConversationMessages(conversation._id, testUserId);
    if (messages.length === 2 && messages[1]?.sources[0]?.page === 2) {
      console.log("✅ Step 9.1: Models test passed successfully!");
    } else {
      throw new Error("Message persistence or source retrieval mismatch.");
    }

    // --------------------------------------------------------------------------
    // Test 2: Step 9.2 Answer Prompt (answer.v1.ts)
    // --------------------------------------------------------------------------
    console.log("\n🧪 2. Testing Step 9.2 Answer Prompt (answer.v1.ts)...");

    const sampleBlocks: ContextBlock[] = [
      {
        index: 1,
        title: "Apple Inc. Form 10-K",
        page: 2,
        text: "Net sales for fiscal 2024 were $391,035 million. Net income was $93,736 million ($93.7 billion). Diluted EPS was $6.08.",
      },
      {
        index: 2,
        title: "Apple Inc. Form 10-K",
        page: 4,
        text: "Cash generated by operating activities was $118,254 million ($118.3 billion). Free cash flow was $108,803 million.",
      },
    ];

    const formattedContext = buildNumberedContext(sampleBlocks);
    console.log("   --- Generated Numbered Context Blocks ---");
    console.log(formattedContext);
    console.log("   ----------------------------------------");

    const { systemPrompt, userPrompt } = buildAnswerPrompt("What was the net profit and operating cash flow in FY24?", sampleBlocks);

    const hasNumberedBlocks = userPrompt.includes("[1] Source: Apple Inc. Form 10-K, page 2") &&
                             userPrompt.includes("[2] Source: Apple Inc. Form 10-K, page 4");
    const hasNotFoundRule = systemPrompt.includes(NOT_FOUND_MESSAGE);
    const hasCitationRule = systemPrompt.includes("[1], [2]");
    const hasStandardsRule = systemPrompt.includes("Company Name") && systemPrompt.includes("Currency and Units");
    const hasDefenseRule = systemPrompt.includes("Prompt Injection");

    if (hasNumberedBlocks && hasNotFoundRule && hasCitationRule && hasStandardsRule && hasDefenseRule) {
      console.log("✅ Step 9.2: Answer prompt rules verified successfully!");
    } else {
      throw new Error("Prompt validation failed: Missing required prompt rules or numbered blocks.");
    }

    // --------------------------------------------------------------------------
    // Test 3: Step 9.3 Refusal Gate Simulation
    // --------------------------------------------------------------------------
    console.log("\n🧪 3. Testing Step 9.3 Refusal Gate...");

    // Refusal test: when query has low similarity score below threshold (e.g. 0.5)
    let refusalTokenReceived = "";
    let refusalSourcesReceived: any = null;

    await chatService.sendMessageAndStream({
      conversationId: conversation._id,
      userId: testUserId,
      content: "What is the secret baking recipe for cinnamon rolls?",
      refusalThreshold: 0.999, // Force refusal gate to test refusal branch
      handlers: {
        onSources: (data) => {
          refusalSourcesReceived = data.sources;
        },
        onToken: (data) => {
          refusalTokenReceived += data.text;
        },
      },
    });

    console.log(`   Refusal response received : "${refusalTokenReceived}"`);
    console.log(`   Sources attached          : ${refusalSourcesReceived?.length || 0}`);

    if (refusalTokenReceived === NOT_FOUND_MESSAGE && refusalSourcesReceived?.length === 0) {
      console.log("✅ Step 9.3: Refusal Gate test passed successfully!");
    } else {
      throw new Error(`Refusal gate failed. Expected "${NOT_FOUND_MESSAGE}", got "${refusalTokenReceived}"`);
    }

    // --------------------------------------------------------------------------
    // Test 4: Step 10.5 Citation Validation on Backend
    // --------------------------------------------------------------------------
    console.log("\n🧪 4. Testing Step 10.5 Citation Validation...");

    const textWithFakeCitations = "Apple reported $94.9B revenue [1] and expanded gross margin [2]. Fake metric [5] and hallucinated stat [9].";
    const cleanedText = validateCitations(textWithFakeCitations, 2);
    console.log(`   Original: "${textWithFakeCitations}"`);
    console.log(`   Cleaned : "${cleanedText}"`);

    if (cleanedText.includes("[1]") && cleanedText.includes("[2]") && !cleanedText.includes("[5]") && !cleanedText.includes("[9]")) {
      console.log("✅ Step 10.5: Backend citation validation successfully stripped invalid [n] tags!");
    } else {
      throw new Error("validateCitations failed to strip invalid citations.");
    }

    // --------------------------------------------------------------------------
    // Test 5: Step 11.1 Query Rewriting for Follow-up Questions
    // --------------------------------------------------------------------------
    console.log("\n🧪 5. Testing Step 11.1 Query Rewriting for Follow-ups...");

    const sampleHistory = [
      { role: "user", content: "What was Apple's total net sales for fiscal year 2024?" },
      { role: "assistant", content: "For fiscal year 2024, Apple Inc. reported total net sales of $391.0 billion [1]." },
    ];

    const followUpQuestion = "What about their net profit?";
    console.log(`   Original Follow-up Question: "${followUpQuestion}"`);

    const rewritten = await rewriteQueryForFollowUp(followUpQuestion, sampleHistory);
    console.log(`   Rewritten Standalone Query : "${rewritten}"`);

    // Verify rewritten query resolves pronouns and includes company or fiscal context
    const hasCompanyOrContext = rewritten.toLowerCase().includes("apple") || rewritten.toLowerCase().includes("2024") || rewritten.toLowerCase().includes("net profit");
    if (hasCompanyOrContext) {
      console.log("✅ Step 11.1: Query Rewriting successfully produced standalone question!");
    } else {
      console.warn("⚠️ Query rewriting returned:", rewritten);
    }

    // --------------------------------------------------------------------------
    // Test 6: Step 11.2 Metadata Filters & Anti-Hallucination Validation
    // --------------------------------------------------------------------------
    console.log("\n🧪 6. Testing Step 11.2 Metadata Filters & Validation...");

    // Create a ready test document for testUserId to match against
    const testDoc = await DocumentModel.create({
      userId: testUserId,
      title: "Apple_Inc_FY24_10K.pdf",
      company: "Apple Inc.",
      docType: "10-K",
      fiscalYear: 2024,
      storageKey: "test/storage/apple_fy24.pdf",
      fileHash: "abc123hash",
      fileSize: 1024,
      status: "indexed",
    });

    const testQuestion = "What was Apple's gross margin in FY24?";
    console.log(`   Sample Question: "${testQuestion}"`);

    const detectedMeta = await detectMetadataFromQuery(testQuestion);
    console.log(`   Detected Metadata: company="${detectedMeta.company}", fiscalYear=${detectedMeta.fiscalYear}`);

    if (detectedMeta.company?.toLowerCase().includes("apple") && detectedMeta.fiscalYear === 2024) {
      console.log("   ✓ Small model correctly extracted company and normalized FY24 -> 2024");
    } else {
      throw new Error(`Metadata detection failed: ${JSON.stringify(detectedMeta)}`);
    }

    const matchedFilters = await matchMetadataAgainstUserDocuments(detectedMeta, testUserId);
    console.log("   Matched Filters against user documents:", matchedFilters);

    if (matchedFilters.fiscalYear === 2024 && matchedFilters.documentId?.toString() === testDoc._id.toString()) {
      console.log("   ✓ Successfully matched against user's actual document records!");
    } else {
      throw new Error("Metadata matching against user documents failed.");
    }

    // Anti-hallucination test: asking about Tesla when user only owns Apple documents
    console.log("   Testing Anti-Hallucination: querying non-owned company 'Tesla'...");
    const fakeDetected = { company: "Tesla Motors", fiscalYear: 2023 };
    const fakeFilters = await matchMetadataAgainstUserDocuments(fakeDetected, testUserId);
    console.log("   Anti-hallucination Filters Result:", fakeFilters);

    if (!fakeFilters.documentId && !fakeFilters.fiscalYear) {
      console.log("   ✓ Anti-Hallucination verified: rejected hallucinated company not in user documents!");
      console.log("✅ Step 11.2: Metadata Filters test passed successfully!");
    } else {
      throw new Error("Anti-hallucination failed: accepted non-existent document metadata!");
    }

    await DocumentModel.findByIdAndDelete(testDoc._id);

    // --------------------------------------------------------------------------
    // Cleanup
    // --------------------------------------------------------------------------
    await chatService.deleteConversation(conversation._id, testUserId);
    console.log("\n🧹 Test conversation and messages cleaned up successfully.");

    await mongoose.disconnect();
    console.log("\n🎉 Step 9: All Chat components passed successfully!");
  } catch (error: any) {
    console.error("\n❌ Step 9 test error:", error?.message || error);
    process.exitCode = 1;
    if (mongoose.connection.readyState !== 0) {
      await mongoose.disconnect();
    }
  }
}

runTest();
